from typing import Optional

def _text(*fields) -> str:
    """Flatten fields into a single searchable string."""
    parts = []
    for f in fields:
        if isinstance(f, str):
            parts.append(f)
        elif isinstance(f, list):
            parts.extend(str(x) for x in f)
    return " ".join(parts)


