# ── Build corpus with searchable _text field ──────────────────────────────────

def _build_corpus() -> list[dict]:
    corpus = []
    for docs in [_ICD10, _CPT, _DENIAL_PATTERNS, _INSURANCE_POLICIES]:
        for doc in docs:
            d = dict(doc)
            # Concatenate all string/list fields for BM25 indexing
            parts = []
            for k, v in d.items():
                if k in ("id", "type"):
                    continue
                if isinstance(v, str):
                    parts.append(v)
                elif isinstance(v, list):
                    parts.extend(str(x) for x in v)
            d["_text"] = " ".join(parts)
            corpus.append(d)
    return corpus


CORPUS: list[dict] = _build_corpus()


def get_document(doc_id: str) -> Optional[dict]:
    """Look up a document by ID."""
    return next((d for d in CORPUS if d["id"] == doc_id), None)
